// @ts-check
// Pure helpers for turning tokens/design-tokens.json into CSS, TypeScript and a Tailwind preset.

/** @typedef {{ [key: string]: string | TokenTree }} TokenTree */

/**
 * Flatten a nested token tree into `[path[], value]` pairs.
 * @param {TokenTree} tree
 * @param {string[]} [prefix]
 * @returns {[string[], string][]}
 */
export function flatten(tree, prefix = []) {
  /** @type {[string[], string][]} */
  const out = [];
  for (const [key, value] of Object.entries(tree)) {
    if (key.startsWith('$')) continue;
    const path = [...prefix, key];
    if (typeof value === 'string') out.push([path, value]);
    else out.push(...flatten(value, path));
  }
  return out;
}

/** @param {string[]} path */
export const cssVarName = (path) => `--ds-${path.join('-')}`;

const REF = /^\{([^}]+)\}$/;

/**
 * Resolve a possible `{a.b.c}` reference against the primitive tokens.
 * @param {string} value
 * @param {TokenTree} primitive
 * @returns {string}
 */
export function resolveValue(value, primitive) {
  const match = REF.exec(value);
  if (!match?.[1]) return value;
  /** @type {string | TokenTree | undefined} */
  let node = primitive;
  for (const part of match[1].split('.')) {
    node = typeof node === 'object' ? node[part] : undefined;
  }
  if (typeof node !== 'string') throw new Error(`Unresolved token reference: ${value}`);
  return node;
}

/**
 * Emit `--ds-*` declarations. References become `var(--ds-*)` so themes stay live.
 * @param {[string[], string][]} entries
 */
function declarations(entries) {
  return entries
    .map(([path, value]) => {
      const ref = REF.exec(value);
      const css = ref?.[1] ? `var(${cssVarName(ref[1].split('.'))})` : value;
      return `  ${cssVarName(path)}: ${css};`;
    })
    .join('\n');
}

/** @param {{ primitive: TokenTree, theme: Record<string, TokenTree> }} tokens */
export function buildCss(tokens) {
  const light = flatten(tokens.theme.light ?? {});
  const dark = flatten(tokens.theme.dark ?? {});
  return `/* GENERATED by scripts/build-tokens.mjs from tokens/design-tokens.json. Do not edit. */
@layer tokens {
  :root {
    color-scheme: light;
${declarations(flatten(tokens.primitive)).replace(/^ {2}/gm, '    ')}
${declarations(light).replace(/^ {2}/gm, '    ')}
  }

  [data-theme='dark'] {
    color-scheme: dark;
${declarations(dark).replace(/^ {2}/gm, '    ')}
  }
}
`;
}

/**
 * Resolve a theme's semantic colors to concrete values.
 * @param {{ primitive: TokenTree, theme: Record<string, TokenTree> }} tokens
 * @param {string} name
 */
function resolvedTheme(tokens, name) {
  return Object.fromEntries(
    flatten(tokens.theme[name] ?? {}).map(([path, value]) => [
      path.join('.'),
      resolveValue(value, tokens.primitive),
    ]),
  );
}

/** @param {{ primitive: TokenTree, theme: Record<string, TokenTree> }} tokens */
export function buildTs(tokens) {
  const data = {
    ...tokens.primitive,
    theme: { light: resolvedTheme(tokens, 'light'), dark: resolvedTheme(tokens, 'dark') },
  };
  return `// GENERATED by scripts/build-tokens.mjs from tokens/design-tokens.json. Do not edit.
export const tokens = ${JSON.stringify(data, null, 2)} as const;

export type Tokens = typeof tokens;
`;
}

/**
 * Walk a sub-tree of the primitive tokens, e.g. `subtree(tokens, 'font', 'size')`.
 * @param {{ primitive: TokenTree }} tokens
 * @param {string[]} path
 * @returns {TokenTree}
 */
function subtree(tokens, path) {
  /** @type {string | TokenTree | undefined} */
  let node = tokens.primitive;
  for (const part of path) node = typeof node === 'object' ? node[part] : undefined;
  if (typeof node !== 'object') throw new Error(`Missing token group: ${path.join('.')}`);
  return node;
}

/** @param {{ primitive: TokenTree, theme: Record<string, TokenTree> }} tokens */
export function buildTailwindPreset(tokens) {
  /**
   * Map every leaf of a group to `var(--ds-<group>-<leaf>)`, keyed as `ds-<leaf>`.
   * @param {string[]} group
   */
  const cssVars = (group) =>
    Object.fromEntries(
      flatten(subtree(tokens, group)).map(([leaf]) => [
        `ds-${leaf.join('.')}`,
        `var(${cssVarName([...group, ...leaf])})`,
      ]),
    );

  // Static palettes (so Tailwind opacity modifiers keep working) ...
  const palettes = Object.fromEntries(
    ['brand', 'neutral', 'green', 'amber', 'red', 'sky'].map((name) => [
      name,
      Object.fromEntries(
        flatten(subtree(tokens, ['color', name])).map(([leaf, value]) => [leaf.join('.'), value]),
      ),
    ]),
  );
  // ... and theme-aware semantic colors, usable as `bg-ds-surface`, `text-ds-text`, etc.
  const semantic = Object.fromEntries(
    flatten(tokens.theme.light ?? {}).map(([path]) => [
      path.slice(1).join('-'),
      `var(${cssVarName(path)})`,
    ]),
  );

  const preset = {
    theme: {
      extend: {
        colors: { ...palettes, ds: semantic },
        spacing: cssVars(['space']),
        borderRadius: cssVars(['radius']),
        boxShadow: cssVars(['shadow']),
        fontSize: cssVars(['font', 'size']),
        fontFamily: {
          'ds-sans': [`var(${cssVarName(['font', 'family', 'sans'])})`],
          'ds-mono': [`var(${cssVarName(['font', 'family', 'mono'])})`],
        },
      },
    },
  };
  return `/* GENERATED by scripts/build-tokens.mjs from tokens/design-tokens.json. Do not edit. */
/** Dhanush Design System Tailwind preset (Tailwind CSS v3). */
module.exports = ${JSON.stringify(preset, null, 2)};
`;
}
